"""Generate the packaged JSON Schema of the public report dataclasses, offline.

Run with the project's Python environment; --check verifies the committed resource. This is
development tooling only: importing astra.model never generates or loads a schema.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Mapping
from dataclasses import fields, is_dataclass
from pathlib import Path
from types import UnionType
from typing import Any, Literal, Union, get_args, get_origin, get_type_hints

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from astra.model.resolved_analysis import ResolvedAnalysis  # noqa: E402
from astra.model.status_report import StatusReport  # noqa: E402
from astra.model.validation_report import ValidationReport  # noqa: E402

REPORTS = (ResolvedAnalysis, ValidationReport, StatusReport)
DESTINATION = ROOT / "src" / "astra" / "model" / "reports.schema.json"


def optional(annotation: Any) -> bool:
    """Whether to_json omits this field when its value is None."""
    return get_origin(annotation) in (Union, UnionType) and type(None) in get_args(annotation)


def generate() -> dict[str, Any]:
    """The report schema, following model.to_json's omission and collection conventions."""
    definitions: dict[str, Any] = {}

    def describe(annotation: Any) -> dict[str, Any]:
        origin, args = get_origin(annotation), get_args(annotation)
        if optional(annotation):
            (value,) = (each for each in args if each is not type(None))
            return describe(value)
        if origin is Literal:
            return {"const": args[0]} if len(args) == 1 else {"enum": list(args)}
        if origin is tuple and len(args) == 2 and args[1] is Ellipsis:
            return {"type": "array", "items": describe(args[0])}
        if origin is Mapping and args[0] is str:
            return {"type": "object", "additionalProperties": describe(args[1])}
        if annotation in (str, int, float, bool):
            return {
                "type": {str: "string", int: "integer", float: "number", bool: "boolean"}[
                    annotation
                ]
            }
        if is_dataclass(annotation):
            name = annotation.__name__
            if name not in definitions:
                definitions[name] = {}  # register before following nested dataclasses
                hints = get_type_hints(annotation)
                properties = {
                    field.name: describe(hints[field.name]) for field in fields(annotation)
                }
                definitions[name] = {
                    "type": "object",
                    "properties": properties,
                    "required": [
                        field.name
                        for field in fields(annotation)
                        if not optional(hints[field.name])
                    ],
                }
            return {"$ref": f"#/$defs/{name}"}
        raise TypeError(f"No JSON representation for {annotation!r}")

    reports = [describe(report) for report in REPORTS]
    return {
        "$schema": "https://json-schema.org/draft/2019-09/schema",
        "$id": "urn:astra-tools:reports:v1",
        "title": "ASTRA public reports",
        "$comment": "Generated by scripts/generate-report-schema.py from astra.model. Do not edit.",
        "oneOf": reports,
        "$defs": dict(sorted(definitions.items())),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Fail if the packaged schema is stale."
    )
    args = parser.parse_args()
    content = json.dumps(generate(), indent=2, ensure_ascii=False) + "\n"
    if args.check:
        if not DESTINATION.is_file() or DESTINATION.read_text("utf-8") != content:
            parser.exit(1, "Report schema is stale; run scripts/generate-report-schema.py.\n")
    else:
        DESTINATION.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
